-- Ajustes configurables (clave/valor): plantilla de WhatsApp y número del gimnasio.
-- Ejecutar en el SQL Editor de Supabase.
create table if not exists settings (
  id bigint generated by default as identity primary key,
  key text not null unique,
  value text not null default ''
);

alter table settings enable row level security;
drop policy if exists "acceso app" on settings;
create policy "acceso app" on settings for all to anon, authenticated using (true) with check (true);

insert into settings (id, key, value)
overriding system value values
  (1, 'whatsapp_template', 'Hola {nombre}, te recordamos tu pago de Studio Functional Fitness: {concepto} por {importe}, que {vencimiento}. ¿Te ayudamos con algo?'),
  (2, 'whatsapp_number', '')
on conflict (id) do nothing;

select setval(pg_get_serial_sequence('settings', 'id'), coalesce((select max(id) from settings), 1));
