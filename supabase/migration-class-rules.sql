-- Horarios semanales (clases en serie). Ejecutar en el SQL Editor de Supabase.
-- Crea las tablas class_rules y class_rule_skips y siembra las 2 reglas Hyrox
-- (lunes a viernes, 18:00 y 19:00, coach Jesus, capacidad 12).
-- La serie de las 7:00 se eliminó el 2026-11-28: desde el viernes 4 dic ya no hay Hyrox 7 am.
-- Las 12 clases sueltas ya sembradas coinciden con estas reglas y no se duplican:
-- la app las fusiona al generar las sesiones semanales.
create table if not exists class_rules (
  id bigint generated by default as identity primary key,
  title text not null,
  type text not null default 'Sesión grupal',
  days integer[] not null default '{}',
  start_date date not null,
  start_time text not null,
  duration_min integer not null default 60,
  capacity integer not null default 12,
  coach text not null default '',
  notes text not null default '',
  active boolean not null default true
);

create table if not exists class_rule_skips (
  id bigint generated by default as identity primary key,
  rule_id bigint not null references class_rules(id) on delete cascade,
  date date not null,
  unique (rule_id, date)
);

alter table class_rules enable row level security;
alter table class_rule_skips enable row level security;

drop policy if exists "acceso app" on class_rules;
create policy "acceso app" on class_rules for all to anon, authenticated using (true) with check (true);
drop policy if exists "acceso app" on class_rule_skips;
create policy "acceso app" on class_rule_skips for all to anon, authenticated using (true) with check (true);

insert into class_rules (id, title, type, days, start_date, start_time, duration_min, capacity, coach, notes, active)
overriding system value values
  (2, 'Hyrox', 'Sesión grupal', array[1,2,3,4,5], '2026-11-27', '18:00', 60, 12, 'Jesus', '', true),
  (3, 'Hyrox', 'Sesión grupal', array[1,2,3,4,5], '2026-11-27', '19:00', 60, 12, 'Jesus', '', true)
on conflict (id) do nothing;

select setval(pg_get_serial_sequence('class_rules', 'id'), coalesce((select max(id) from class_rules), 1));
select setval(pg_get_serial_sequence('class_rule_skips', 'id'), coalesce((select max(id) from class_rule_skips), 1));
